def norm(text: str) -> str:
    """ё→е без смены длины: смещения совпадают с исходным текстом."""
    return text.replace("ё", "е").replace("Ё", "Е")


def read_text(path: str | None) -> str:
    if not path or path == "-":
        data = sys.stdin.buffer.read()
    else:
        data = Path(path).read_bytes()
    for encoding in ("utf-8-sig", "cp1251"):
        try:
            return data.decode(encoding).replace("\r\n", "\n").replace("\r", "\n")
        except UnicodeDecodeError:
            continue
    return data.decode("utf-8", errors="replace").replace("\r\n", "\n")


def blank(text: str, start: int, end: int, fill: str = " ") -> str:
    chunk = "".join("\n" if ch == "\n" else fill for ch in text[start:end])
    return text[:start] + chunk + text[end:]


def mask_code(text: str) -> str:
    for rx in (r"```.*?(?:```|$)", r"~~~.*?(?:~~~|$)"):
        for m in list(re.finditer(rx, text, re.S)):
            text = blank(text, m.start(), m.end())
    for m in list(re.finditer(r"`[^`\n]+`", text)):
        text = blank(text, m.start(), m.end(), "x")
    for m in list(re.finditer(r"https?://\S+|www\.\S+", text)):
        text = blank(text, m.start(), m.end(), "x")
    return text


def mask_quotes(text: str) -> str:
    for rx in (r"«[^«»\n]{1,300}»", r"\"[^\"\n]{1,300}\"", r"“[^“”\n]{1,300}”", r"„[^„“\n]{1,300}“",
               r"(?m)^[ \t]*>.*$"):
        for m in list(re.finditer(rx, text)):
            text = blank(text, m.start(), m.end())
    return text


