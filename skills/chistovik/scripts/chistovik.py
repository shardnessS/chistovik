def number_key(m: re.Match) -> str | None:
    if m.group("n"):
        digits = re.sub(r"[   ]", "", m.group("n")).replace(",", ".")
        try:
            value = float(digits)
        except ValueError:
            return None
    elif m.group("w"):
        total, current = 0.0, 0.0
        for word in m.group("w").lower().split():
            v = NUMERAL_VALUE[word]
            if v == 1000:
                total += max(current, 1) * 1000
                current = 0
            else:
                current += v
        value = total + current
    else:
        return None
    lat = (m.group("lat") or "").lower()
    if lat:
        value *= MAG[lat]
    mag = (m.group("mag") or "").lower().rstrip(".")
    for prefix, factor in MAG.items():
        if mag and mag.startswith(prefix):
            value *= factor
            break
    unit = (m.group("u") or "").lower()
    unit_class = ""
    if unit:
        for prefix in sorted(UNIT_CLASS, key=len, reverse=True):
            if unit.startswith(prefix):
                unit_class = UNIT_CLASS[prefix]
                break
    if m.group("c1"):
        unit_class = UNIT_CLASS[m.group("c1")]
    qual = QUAL_CLASS.get((m.group("q") or "").lower(), "")
    shown = str(int(value)) if float(value).is_integer() else f"{value:.6f}".rstrip("0").rstrip(".")
    return f"{qual}{shown}{(' ' + unit_class) if unit_class else ''}"


def mid_sentence_names(text: str) -> list[str]:
    names = []
    for m in re.finditer(r"(?<=[\w,;:)»\"]\s)([А-ЯЁ][а-яё]{1,}(?:-[А-ЯЁ][а-яё]+)?)", text):
        word = m.group(1)
        if word.lower() in ("вы", "вас", "вам", "вами", "ваш", "ваша", "ваше", "ваши", "вашего", "вашей", "вашему",
                            "вашим", "вашем", "вашу", "ваших"):
            continue
        names.append(word)
    return names


def extract_facts(text: str) -> dict:
    t = norm(text)
    facts = {"числа": [], "даты": [], "имена": [], "латиница": [], "аббревиатуры": [], "точные": []}
    rest = t
    for kind, rx in EXACT_RES.items():
        for m in rx.finditer(rest):
            facts["точные"].append(f"{kind}: {m.group()}")
        rest = rx.sub(lambda m: " " * len(m.group()), rest)
    for m in NUMBER_RE.finditer(rest):
        if not (m.group("n") or m.group("w")):
            continue
        key = number_key(m)
        if key:
            facts["числа"].append((key, text[m.start():m.end()].strip()))
    for word, key in MULTIPLIERS.items():
        for m in re.finditer(r"\b" + word + r"\b", rest, re.I):
            facts["числа"].append((key, word))
    for m in MONTH_RE.finditer(rest):
        facts["даты"].append(m.group(1).lower()[:3])
    for m in WEEKDAY_RE.finditer(rest):
        facts["даты"].append(m.group(1).lower()[:4])
    facts["латиница"] = [w for w in re.findall(r"\b[A-Za-z][A-Za-z0-9+#.-]*[A-Za-z0-9+#]|\b[A-Za-z]{2,}\b", rest)]
    facts["аббревиатуры"] = re.findall(r"\b[А-ЯЁ]{2,}\b", rest)
    facts["имена"] = mid_sentence_names(rest)
    return facts


def count_regex(rx: str, text: str) -> int:
    return len(re.findall(r"\b(?:" + rx + r")\b", norm(text), re.I))


def check(original: str, revised: str, genre: str = DEFAULT_GENRE, new_text: bool = False) -> dict:
    fo, fr = extract_facts(original), extract_facts(revised)
    errors, warnings = [], []

    o_nums = {k: s for k, s in fo["числа"]}
    r_nums = {k: s for k, s in fr["числа"]}
    value = lambda key: key.lstrip("~<>").split(" ")[0]  # noqa: E731

    def base(shown: str) -> str:
        m = re.search(r"\d[\d   ]*(?:[.,]\d+)?", shown)
        return re.sub(r"\s", "", m.group()).rstrip(".,") if m else shown.lower()

    def unit(key: str) -> str:
        return key.split(" ", 1)[1] if " " in key else ""

    def same_fact(a: str, k: str) -> bool:
        # В правке «150 км» → «150 миль» — то же число с другой единицей.
        # В новом тексте исходные числа не обязаны встречаться, поэтому «6 часов» и «шесть лет» — разные факты.
        if new_text and unit(a) and unit(k) and unit(a) != unit(k):
            return False
        return value(a) == value(k) or base(r_nums[a]) == base(o_nums[k])

    lost = [k for k in o_nums if k not in r_nums]
    added = [k for k in r_nums if k not in o_nums]
    for k in list(lost):
        twin = next((a for a in added if same_fact(a, k)), None)
        if twin:
            errors.append(f"Число изменилось: было «{o_nums[k]}», стало «{r_nums[twin]}».")
            lost.remove(k)
            added.remove(twin)
    if not new_text:
        for k in lost:
            errors.append(f"Пропало число: «{o_nums[k]}».")
    for k in added:
        errors.append(f"Появилось число, которого не было: «{r_nums[k]}».")

    def lost_items(kind: str, key=lambda x: x) -> list[str]:
        have = {key(x) for x in fr[kind]}
        seen, out = set(), []
        for x in fo[kind]:
            if key(x) not in have and key(x) not in seen:
                seen.add(key(x))
                out.append(x)
        return out

    def added_items(kind: str, key=lambda x: x) -> list[str]:
        have = {key(x) for x in fo[kind]}
        return sorted({x for x in fr[kind] if key(x) not in have})

    labels = {"даты": "месяц или день недели", "латиница": "название", "аббревиатуры": "аббревиатура",
              "точные": "точное значение"}
    for kind, label in labels.items():
        key = (lambda x: x.lower()) if kind == "латиница" else (lambda x: x)
        if not new_text:
            for x in lost_items(kind, key):
                errors.append(f"Пропало {label}: «{x}».")
        for x in added_items(kind, key):
            (warnings if kind == "латиница" else errors).append(f"Появилось {label}, которого не было: «{x}».")

    if not new_text:
        revised_words = [w.lower() for w in words(norm(revised))]
        for name in dict.fromkeys(fo["имена"]):
            stem = norm(name).lower()[:max(2, min(5, len(name) - 1))]
            if not any(w.startswith(stem) for w in revised_words):
                errors.append(f"Пропало имя или название: «{name}».")

        neg_o = len(NEGATION_RE.findall(norm(original))) - len(NEGATION_FILLER_RE.findall(norm(original)))
        neg_r = len(NEGATION_RE.findall(norm(revised))) - len(NEGATION_FILLER_RE.findall(norm(revised)))
        if neg_r < neg_o:
            warnings.append(f"Отрицаний было {neg_o}, стало {neg_r}. Перечитай, не перевернулся ли смысл.")
        for word, rx in SCOPE_WORDS.items():
            a, b = count_regex(rx, original), count_regex(rx, revised)
            if b < a:
                warnings.append(f"Слов вроде «{word}» было {a}, стало {b}. Проверь, не изменились требования и границы.")
        for q in re.findall(r"«([^«»\n]{1,80})»|\"([^\"\n]{1,80})\"", original):
            content = q[0] or q[1]
            if norm(content).lower() not in norm(revised).lower():
                warnings.append(f"Пропала цитата или название в кавычках: «{content}».")

    so, sr = scan(original, genre), scan(revised, genre)
    old = {(f["id"], norm(f["span"]).lower()) for f in so["findings"]}
    introduced = [f for f in sr["findings"] if (f["id"], norm(f["span"]).lower()) not in old]
    for f in introduced:
        line = f"Новая находка: {f['category_name']} [{f['id']}] «{f['span'][:80]}». {f['hint']}"
        (errors if f["severity"] == "hard" else warnings).append(line)
    remaining = [f for f in sr["findings"] if f["severity"] == "hard" and f not in introduced]
    for f in remaining:
        warnings.append(f"Осталась жёсткая находка: {f['category_name']} [{f['id']}] «{f['span'][:80]}». "
                        "Если оставлена намеренно, объясни почему.")

    ow, rw = words(original), words(revised)
    ratio = difflib.SequenceMatcher(None, [w.lower() for w in ow], [w.lower() for w in rw], autojunk=False).ratio()
    changed = round(100 * (1 - ratio))
    too_long_chat = genre == "chat" and any(f["id"] == "dlinny_chat" for f in so["findings"])
    if not new_text and changed > 50 and not too_long_chat:
        warnings.append(f"Изменено около {changed}% слов. Для правки это много: правь только найденные места.")
    verdict = "fail" if errors else ("warn" if warnings else "pass")
    return {"verdict": verdict, "errors": errors, "warnings": warnings, "changed_percent": changed,
            "words_before": len(ow), "words_after": len(rw), "hard_before": so["hard"], "hard_after": sr["hard"],
            "soft_before": so["soft"], "soft_after": sr["soft"], "mode": "new" if new_text else "edit"}


def format_check(result: dict) -> str:
    title = {"pass": "Проверка пройдена.", "warn": "Пройдена, но есть предупреждения.",
             "fail": "Проверка не пройдена."}[result["verdict"]]
    lines = [f"Чистовик {VERSION}: {title}",
             f"Слов было {result['words_before']}, стало {result['words_after']}, изменено около "
             f"{result['changed_percent']}%. Жёстких находок было {result['hard_before']}, стало {result['hard_after']}; "
             f"спорных было {result['soft_before']}, стало {result['soft_after']}."]
    if result["errors"]:
        lines += ["", "Ошибки:"] + [f"  - {e}" for e in result["errors"]]
    if result["warnings"]:
        lines += ["", "Предупреждения:"] + [f"  - {w}" for w in result["warnings"]]
    return "\n".join(lines)


