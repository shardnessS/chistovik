def resolve_genre(value: str | None) -> str:
    if not value:
        return DEFAULT_GENRE
    key = value.strip().lower()
    if key in GENRES:
        return key
    for genre, (_, aliases) in GENRES.items():
        if key in aliases:
            return genre
    raise SystemExit(f"Неизвестный жанр «{value}». Список: python chistovik.py genres")


