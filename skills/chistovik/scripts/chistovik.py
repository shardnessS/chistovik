def voice_metrics(text: str) -> dict:
    t = mask_code(norm(text).replace("\r", ""))
    raw = mask_code(text.replace("\r", ""))
    items = blocks(t)
    prose = [b for b in items if b["kind"] in ("prose", "list")]
    sentences = [s for b in prose for s in split_sentences(b["text"], b["start"])]
    lengths = [len(words(s[2])) for s in sentences] or [0]
    ws = words(t)
    n = max(len(ws), 1)
    per = lambda count: round(count * 1000 / n, 2)  # noqa: E731
    lowercase = sum(1 for s in sentences if re.match(r"[а-яa-z]", s[2]))
    connective = sum(1 for s in sentences if starts_with_any(s[2], CONNECTIVES))
    return {
        "words": len(ws),
        "sentence_mean": round(statistics.mean(lengths), 2),
        "sentence_sd": round(statistics.pstdev(lengths), 2) if len(lengths) > 1 else 0.0,
        "paragraph_sentences": round(len(sentences) / max(len(prose), 1), 2),
        "dash": per(len(re.findall(r"(?<=\s)[—–](?=\s)", t))),
        "guillemets": per(t.count("«")),
        "straight_quotes": per(t.count('"') / 2),
        "exclamation": per(len(re.findall(r"!+", t))),
        "question": per(len(re.findall(r"\?+", t))),
        "ellipsis": per(len(re.findall(r"\.{3}|…", t))),
        "parens": per(len(re.findall(r"\([^)\n]{2,}\)", t))),
        "colon": per(t.count(":")),
        "smiley": per(len(SMILEY_RE.findall(t))),
        "emoji": per(len(EMOJI_RE.findall(t))),
        "yo": per(raw.count("ё") + raw.count("Ё")),
        "lowercase_start": round(100 * lowercase / max(len(sentences), 1), 1),
        "first_person": per(len(FIRST_PERSON_RE.findall(t))),
        "we": per(len(WE_RE.findall(t))),
        "ty": per(len(TY_RE.findall(t))),
        "vy": per(len(VY_RE.findall(t))),
        "colloquial": per(len(COLLOQUIAL_RE.findall(t))),
        "connective_openers": round(100 * connective / max(len(sentences), 1), 1),
        "word_length": round(sum(len(w) for w in ws) / n, 2),
    }


def sample_files(paths: list[Path]) -> list[Path]:
    files = []
    for p in paths:
        if p.is_dir():
            files += sorted(x for x in p.rglob("*") if x.suffix.lower() in (".txt", ".md") and x.is_file())
        elif p.is_file():
            files.append(p)
    return files


def build_voice(name: str, sources: list[str]) -> dict:
    if not re.fullmatch(r"[\w-]{1,40}", name):
        raise SystemExit("Имя голоса: буквы, цифры, дефис и подчёркивание, до 40 символов.")
    home = golos_home() / name
    samples = home / "samples"
    samples.mkdir(parents=True, exist_ok=True)
    for src in sample_files([Path(s) for s in sources]):
        target = samples / src.name
        i = 2
        while target.exists() and target.read_bytes() != src.read_bytes():
            target = samples / f"{src.stem}-{i}{src.suffix}"
            i += 1
        if not target.exists():
            shutil.copyfile(src, target)
    files = sample_files([samples])
    if not files:
        raise SystemExit(f"Нет образцов. Положи .txt или .md в {samples} или передай файлы командой build.")
    texts = [read_text(str(f)) for f in files]
    joined = "\n\n".join(texts)
    metrics = voice_metrics(joined)
    per_sample = [voice_metrics(t) for t in texts if len(words(t)) >= 30]
    spread = {}
    for key, *_ in MARKERS:
        values = [m[key] for m in per_sample]
        spread[key] = round(statistics.pstdev(values), 2) if len(values) >= 2 else None
    openers = Counter(first_words(s[2], 1) for t in texts for b in blocks(mask_code(norm(t)))
                      if b["kind"] == "prose" for s in split_sentences(b["text"]))
    phrases = []
    for t in texts:
        for b in blocks(mask_code(t)):
            if b["kind"] != "prose":
                continue
            for s in split_sentences(b["text"]):
                if 6 <= len(words(s[2])) <= 22 and not scan(s[2], "chat")["findings"]:
                    phrases.append(s[2])
    step = max(1, len(phrases) // 6)
    profile = {
        "name": name, "version": VERSION, "samples": len(files), "words": metrics["words"],
        "low_confidence": metrics["words"] < 600 or len(files) < 3,
        "metrics": metrics, "spread": spread,
        "openers": [w for w, _ in openers.most_common(6) if w],
        "examples": phrases[::step][:6],
    }
    (home / "profile.json").write_text(json.dumps(profile, ensure_ascii=False, indent=2), encoding="utf-8")
    (home / "card.md").write_text(voice_card(profile), encoding="utf-8")
    return profile


def voice_card(profile: dict) -> str:
    m = profile["metrics"]
    rules = []
    rules.append(f"Предложения в среднем {num(m['sentence_mean'])} слов, разброс {num(m['sentence_sd'])}. "
                 f"В абзаце около {num(m['paragraph_sentences'])} предложений.")
    rules.append("Длинное тире почти не ставит." if m["dash"] < 2 else f"Тире ставит: {num(m['dash'])} на 1000 слов.")
    if m["guillemets"] < 1 and m["straight_quotes"] >= 1:
        rules.append("Кавычки прямые, \"так\", не ёлочки.")
    elif m["guillemets"] >= 1:
        rules.append("Кавычки-ёлочки «так».")
    rules.append("Букву ё не пишет, везде е." if m["yo"] < 1 else "Букву ё пишет.")
    if m["exclamation"] < 2:
        rules.append("Восклицательных знаков почти нет.")
    if m["emoji"] < 1:
        rules.append("Эмодзи не использует.")
    if m["smiley"] >= 2:
        rules.append(f"Ставит смайлики из скобок: {num(m['smiley'])} на 1000 слов.")
    if m["lowercase_start"] >= 30:
        rules.append(f"Часто начинает предложения с маленькой буквы ({num(m['lowercase_start'])}%).")
    if m["ty"] > m["vy"] and m["ty"] >= 3:
        rules.append("К собеседнику на «ты».")
    elif m["vy"] >= 3:
        rules.append("К собеседнику на «вы».")
    rules.append("Пишет от первого лица, «я»." if m["first_person"] >= m["we"] else "Чаще пишет «мы», чем «я».")
    if m["colloquial"] >= 5:
        rules.append(f"Разговорные слова есть: {num(m['colloquial'])} на 1000 слов.")
    else:
        rules.append("Разговорных словечек почти нет.")
    if m["connective_openers"] < 8:
        rules.append("Предложения редко начинает со связок вроде «Кроме того».")
    lines = [f"# Голос: {profile['name']}", "",
             f"Собран по {profile['samples']} образцам, {profile['words']} слов. "
             + ("Образцов мало, это черновой профиль: попроси ещё 2–3 текста того же жанра."
                if profile["low_confidence"] else "Образцов достаточно для чернового сравнения."),
             "", "## Привычки", ""]
    lines += [f"- {r}" for r in rules]
    if profile["openers"]:
        lines += ["", "## Чаще всего начинает предложения со слов", "", ", ".join(profile["openers"])]
    if profile["examples"]:
        lines += ["", "## Фразы из образцов", ""] + [f"> {e}" for e in profile["examples"]]
    lines += ["", "## Правило", "",
              "Пиши по этим привычкам, но не придумывай новых. Голос не отменяет проверку: текст в этом голосе "
              "всё равно должен пройти `scan` без жёстких находок и `check` без потери фактов.", ""]
    return "\n".join(lines)


def load_voice(name: str) -> dict:
    path = golos_home() / name / "profile.json"
    if not path.is_file():
        raise SystemExit(f"Голос «{name}» не найден. Список: python chistovik.py golos list")
    return json.loads(path.read_text(encoding="utf-8"))


def compare_voice(profile: dict, text: str) -> dict:
    target = voice_metrics(text)
    rows = []
    for key, label, unit, noise in MARKERS:
        p, x = profile["metrics"][key], target[key]
        scale = max(noise, abs(p) * 0.5, (profile.get("spread") or {}).get(key) or 0)
        dev = min(1.0, abs(x - p) / scale / 2)
        rows.append({"key": key, "label": label, "unit": unit, "profile": p, "text": x, "deviation": round(dev, 2)})
    score = round(100 * (1 - statistics.mean(r["deviation"] for r in rows)))
    worst = sorted((r for r in rows if r["deviation"] >= 0.25), key=lambda r: -r["deviation"])[:4]
    return {"name": profile["name"], "score": score, "words": target["words"], "short": target["words"] < 60,
            "differences": worst, "rows": rows}


def format_compare(result: dict) -> str:
    lines = [f"Чистовик {VERSION}: похожесть на голос «{result['name']}»: {result['score']} из 100."]
    if result["short"]:
        lines.append(f"В тексте всего {result['words']} слов, цифры шумные.")
    if result["differences"]:
        lines.append("Сильнее всего отличается:")
        for r in result["differences"]:
            unit = f" {r['unit']}" if r["unit"] else ""
            lines.append(f"  - {r['label']}: у автора {num(r['profile'])}{unit}, в тексте {num(r['text'])}{unit}")
    else:
        lines.append("Заметных отличий по привычкам нет.")
    lines.append("Это грубая мера по 22 привычкам письма. Она не определяет авторство.")
    return "\n".join(lines)


# --------------------------------------------------------------------------- каталог в markdown

def catalog_markdown() -> str:
    lines = ["# Каталог штампов", "",
             "Файл собирается командой `python scripts/chistovik.py catalog`. Не правь его руками: правила живут "
             "в `scripts/chistovik.py`, тесты проверяют, что каталог совпадает с кодом.", "",
             "Уровни: **жёсткий** почти всегда выдаёт сгенерированный текст, **спорный** зависит от жанра и автора. "
             "Находка сканера только повод перечитать место, а не приговор.", "",
             "Жанры: `chat` сообщение в мессенджере, `cv` резюме и отклик, `letter` деловое письмо, `post` пост, "
             "`article` статья и любой другой текст (по умолчанию), `docs` README и документация, "
             "`official` официальный текст. Подробно в [genres.md](genres.md).", ""]
    sev_name = {"hard": "жёсткий", "soft": "спорный", "off": "не проверяется"}
    for cat, (title, about) in CATEGORIES.items():
        rows = [p for p in PHRASES if p["cat"] == cat]
        checks = [c for c in STRUCTURE_CHECKS if c[1] == cat]
        if not rows and not checks:
            continue
        lines += [f"## {title}", "", about, ""]
        cat_genres = CATEGORY_GENRES.get(cat)
        if cat_genres:
            lines += ["По жанрам: " + ", ".join(f"`{g}` {sev_name[s]}" for g, s in cat_genres.items()) + ".", ""]
        if rows:
            lines += ["| Правило | Уровень | Пример | Как править |", "|---|---|---|---|"]
            for p in rows:
                level = sev_name[p["sev"]]
                if p["genres"]:
                    level += "; " + ", ".join(f"`{g}` {sev_name[s]}" for g, s in p["genres"].items())
                lines.append(f"| `{p['id']}` | {level} | {p['example']} | {p['hint']} |")
            lines.append("")
        for cid, _, sev, about_check, example in checks:
            ex = example.replace("\n", " / ")
            lines.append(f"- `{cid}`, {sev_name[sev]}: {about_check}" + (f" Пример: {ex}" if ex != "—" else ""))
        if checks:
            lines.append("")
    return "\n".join(lines).rstrip() + "\n"


# --------------------------------------------------------------------------- CLI

def main(argv: list[str] | None = None) -> int:
    for stream in (sys.stdout, sys.stderr):
        if hasattr(stream, "reconfigure"):
            stream.reconfigure(encoding="utf-8")
    parser = argparse.ArgumentParser(prog="chistovik", description="Штампы нейросети в русском тексте")
    sub = parser.add_subparsers(dest="cmd", required=True)

    p_scan = sub.add_parser("scan", help="найти штампы")
    p_scan.add_argument("file", nargs="?")
    p_scan.add_argument("--genre", "-g")
    p_scan.add_argument("--json", action="store_true")
    p_scan.add_argument("--include-quoted", action="store_true", help="проверять и текст в кавычках")

    p_check = sub.add_parser("check", help="сверить правку с исходником")
    p_check.add_argument("original")
    p_check.add_argument("revised")
    p_check.add_argument("--genre", "-g")
    p_check.add_argument("--new", action="store_true", help="новый текст по заданию: не искать пропавшие факты")
    p_check.add_argument("--json", action="store_true")

    p_golos = sub.add_parser("golos", help="голос автора")
    gsub = p_golos.add_subparsers(dest="gcmd", required=True)
    g_build = gsub.add_parser("build")
    g_build.add_argument("name")
    g_build.add_argument("sources", nargs="*")
    g_cmp = gsub.add_parser("compare")
    g_cmp.add_argument("name")
    g_cmp.add_argument("file")
    g_cmp.add_argument("--json", action="store_true")
    g_show = gsub.add_parser("show")
    g_show.add_argument("name")
    gsub.add_parser("list")

    sub.add_parser("genres", help="список жанров")
    sub.add_parser("catalog", help="каталог правил в markdown")

    args = parser.parse_args(argv)

    if args.cmd == "scan":
        result = scan(read_text(args.file), resolve_genre(args.genre), args.include_quoted)
        print(json.dumps(result, ensure_ascii=False, indent=2) if args.json else format_scan(result))
        return 0
    if args.cmd == "check":
        result = check(read_text(args.original), read_text(args.revised), resolve_genre(args.genre), args.new)
        print(json.dumps(result, ensure_ascii=False, indent=2) if args.json else format_check(result))
        return 1 if result["verdict"] == "fail" else 0
    if args.cmd == "golos":
        if args.gcmd == "build":
            profile = build_voice(args.name, args.sources)
            home = golos_home() / args.name
            print(f"Голос «{args.name}»: образцов {profile['samples']}, слов {profile['words']}.")
            if profile["low_confidence"]:
                print("Образцов мало: профиль черновой. Лучше 3 текста и от 600 слов одного жанра.")
            print(f"Профиль: {home / 'profile.json'}")
            print(f"Карточка: {home / 'card.md'}")
            return 0
        if args.gcmd == "compare":
            result = compare_voice(load_voice(args.name), read_text(args.file))
            print(json.dumps(result, ensure_ascii=False, indent=2) if args.json else format_compare(result))
            return 0
        if args.gcmd == "show":
            load_voice(args.name)
            print((golos_home() / args.name / "card.md").read_text(encoding="utf-8"))
            return 0
        if args.gcmd == "list":
            home = golos_home()
            names = sorted(p.parent.name for p in home.glob("*/profile.json")) if home.is_dir() else []
            print("\n".join(names) if names else f"Голосов пока нет. Папка: {home}")
            return 0
    if args.cmd == "genres":
        for genre, (title, aliases) in GENRES.items():
            print(f"{genre}: {title}. Можно писать: {', '.join(aliases)}.")
            print(f"  {GENRE_NOTES[genre]}")
        print(f"По умолчанию: {DEFAULT_GENRE}.")
        return 0
    if args.cmd == "catalog":
        sys.stdout.flush()
        sys.stdout.buffer.write(catalog_markdown().encode("utf-8"))  # LF и на Windows
        return 0
    return 2


if __name__ == "__main__":
    sys.exit(main())
